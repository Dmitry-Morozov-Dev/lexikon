# === Normalize POS & emit ===
POS_OK = {"noun","verb","adj","adv","prep","conj","phrase","other"}
POS_MAP = {"number": "other", "num": "other"}

def normalize_pos(pos):
    pos = (pos or "other").lower().strip()
    pos = POS_MAP.get(pos, pos)
    return pos if pos in POS_OK else "other"

def build_cards():
    seen = set()
    cards = []
    TARGET = 880
    for word, ipa, pos, tr, ex, exRu, bucket in RAW:
        if len(cards) >= TARGET:
            break
        key = word.strip().lower()
        if not key or key in seen:
            continue
        seen.add(key)
        # example word count soft check
        if len(ex.split()) > 12:
            # trim is rare; keep as-is but prefer short
            pass
        n = len(cards) + 1
        cid = "a1-%04d" % n
        img = svg(bucket)
        cards.append({
            "id": cid,
            "word": word,
            "lemma": word.lower() if word[:1].isupper() and word.isalpha() and len(word) > 1 else word,
            # Keep lemma as base form: for pronouns etc use word.lower()
            "ipa": ipa,
            "pos": normalize_pos(pos),
            "level": "a1",
            "tr": tr,
            "note": "",
            "ex": ex,
            "exRu": exRu,
            "colloc": "",
            "img": img,
            "imgSrc": "svg",
            "imgAlt": word,
        })
    # Fix lemma to lowercase word form for consistency
    for c in cards:
        c["lemma"] = c["word"].lower()
    return cards

def main():
    cards = build_cards()
    out = Path(__file__).resolve().parents[1] / "data" / "a1.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("Wrote %s cards -> %s" % (len(cards), out))
    if not (700 <= len(cards) <= 900):
        print("WARNING: count %d outside 700–900" % len(cards))

if __name__ == "__main__":
    main()
